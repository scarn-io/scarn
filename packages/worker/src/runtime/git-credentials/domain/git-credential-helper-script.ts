import { CONTAINER_GIT_CREDENTIAL_DIR } from "./git-credential-container-env";

/** File in the helper dir holding the relay base URL. */
export const GIT_CREDENTIAL_ENDPOINT_FILENAME = "endpoint";
/** File in the helper dir holding the relay bearer token. */
export const GIT_CREDENTIAL_TOKEN_FILENAME = "token";

export const GIT_CREDENTIAL_HELPER_MISSING_TOOL_MESSAGE =
  "scarn: git credential helper needs curl or wget in the container";

/**
 * Builds `git-credential-scarn`, the credential helper git runs inside the
 * devcontainer (decisions 6 and 7).
 *
 * It is POSIX `sh` (busybox works). It reads `endpoint` and `token` from its
 * own directory and, for `get`, `store` and `erase`, posts git's request on
 * stdin to `<endpoint>/credentials/git/<operation>`, printing the relay's
 * answer for git. The request body is staged in a temp file (busybox `wget`
 * cannot post stdin). It prefers `curl`, which reads the `Authorization`
 * header from a config on stdin (`-K -`) so the token never appears in argv.
 * The `wget` fallback has no such option, so there the token is in argv for
 * the request's lifetime.
 *
 * It always exits 0, so a failed request leaves git to fail normally.
 */
export function buildGitCredentialHelperScript(): string {
  return `#!/bin/sh
# Scarn git credential helper, mounted at ${CONTAINER_GIT_CREDENTIAL_DIR}.
# Forwards git's credential request on stdin to the worker's per-run relay and
# prints the answer. Always exits 0 so git falls through to its normal failure.
# Generated by the worker - do not edit.

case "\${1:-}" in
  get | store | erase) ;;
  *) exit 0 ;;
esac

dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P) || exit 0
endpoint=$(cat "$dir/${GIT_CREDENTIAL_ENDPOINT_FILENAME}" 2>/dev/null) || exit 0
token=$(cat "$dir/${GIT_CREDENTIAL_TOKEN_FILENAME}" 2>/dev/null) || exit 0
url="$endpoint/credentials/git/$1"

if command -v curl >/dev/null 2>&1; then
  body=$(mktemp) || exit 0
  trap 'rm -f "$body"' EXIT
  cat >"$body"
  printf 'header = "Authorization: Bearer %s"\\n' "$token" |
    curl -fsS --max-time 15 -K - -H "Content-Type: text/plain" \\
      --data-binary "@$body" "$url"
elif command -v wget >/dev/null 2>&1; then
  body=$(mktemp) || exit 0
  trap 'rm -f "$body"' EXIT
  cat >"$body"
  wget -qO- -T 15 --header "Content-Type: text/plain" \\
    --header "Authorization: Bearer $token" --post-file="$body" "$url"
else
  echo "${GIT_CREDENTIAL_HELPER_MISSING_TOOL_MESSAGE}" >&2
fi
exit 0
`;
}
