/**
 * Generates `<server>.tools.ts` from a lock: an `mcpToolCatalog` whose tools
 * carry zod types derived from the JSON Schemas (for inference) and the
 * original JSON Schemas verbatim (for the runtime). The output is
 * deterministic and prettier-clean.
 */
import type {
  JsonSchemaObject,
  JsonValue,
} from "../../contracts/pipeline-document/json";
import {
  callDoc,
  group,
  hardline,
  jsonLiteralDoc,
  objectDoc,
  printDoc,
  stringLiteral,
  type Doc,
} from "./doc-printer";
import { jsonSchemaToZod } from "./json-schema-to-zod";
import type { McpToolLock, McpToolLockTool } from "./lock";
import { mcpToolCatalogExportName, mcpToolKeys } from "./names";

export type GenerateMcpToolCatalogOptions = {
  /** The module that exports `mcpTool`, `mcpToolCatalog` and `z`. */
  readonly importFrom?: string;
};

export type GeneratedMcpToolCatalog = {
  readonly source: string;
  readonly exportName: string;
  /** Catalog key for each tool name, in catalog order. */
  readonly keys: readonly { readonly name: string; readonly key: string }[];
  /** Key collisions and schema features that fell back to `z.unknown()`. */
  readonly warnings: readonly string[];
};

export const DEFAULT_MCP_TOOL_CATALOG_IMPORT = "@scarn/sdk/definitions/steps";

export function generateMcpToolCatalogSource(
  lock: McpToolLock,
  options: GenerateMcpToolCatalogOptions = {},
): GeneratedMcpToolCatalog {
  const importFrom = options.importFrom ?? DEFAULT_MCP_TOOL_CATALOG_IMPORT;
  const exportName = mcpToolCatalogExportName(lock.server);
  const { keys, warnings: keyWarnings } = mcpToolKeys(
    lock.server,
    lock.tools.map((tool) => tool.name),
  );
  const warnings = [...keyWarnings];
  const toolEntries = lock.tools.map((tool, index): readonly [string, Doc] => [
    keys[index]?.key ?? tool.name,
    toolDoc(tool, warnings),
  ]);
  const catalog = callDoc(
    "mcpToolCatalog",
    [
      objectDoc(
        [
          [
            "source",
            objectDoc([
              ["server", stringLiteral(lock.server)],
              ["lockHash", stringLiteral(lock.hash)],
            ]),
          ],
          ["tools", objectDoc(toolEntries, true)],
        ],
        true,
      ),
    ],
    true,
  );
  const header = [
    `// GENERATED by \`scarn mcp pull ${lock.server}\` from ${lock.server}.lock.json. Do not edit.`,
    "// Tool names and schemas only; bind it with `defineMcp(...).withTools(...)`.",
  ];
  const body = printDoc(
    group([
      `import { mcpTool, mcpToolCatalog, z } from ${stringLiteral(importFrom)};`,
      hardline,
      hardline,
      `export const ${exportName} = `,
      catalog,
      ";",
    ]),
  );
  return {
    source: `${header.join("\n")}\n${body}\n`,
    exportName,
    keys,
    warnings,
  };
}

function toolDoc(tool: McpToolLockTool, warnings: string[]): Doc {
  const input = schemaDoc(tool.name, "input", tool.inputSchema, warnings);
  const entries: (readonly [string, Doc])[] = [
    ["name", stringLiteral(tool.name)],
  ];
  if (tool.title !== undefined) {
    entries.push(["title", stringLiteral(tool.title)]);
  }
  if (tool.description !== undefined) {
    entries.push(["description", stringLiteral(tool.description)]);
  }
  entries.push(
    ["input", input],
    ["inputJsonSchema", jsonLiteralDoc(tool.inputSchema as JsonValue)],
  );
  if (tool.outputSchema !== undefined) {
    entries.push(
      ["output", schemaDoc(tool.name, "output", tool.outputSchema, warnings)],
      ["outputJsonSchema", jsonLiteralDoc(tool.outputSchema as JsonValue)],
    );
  }
  return callDoc("mcpTool", [objectDoc(entries, true)], true);
}

function schemaDoc(
  toolName: string,
  which: "input" | "output",
  schema: JsonSchemaObject,
  warnings: string[],
): Doc {
  const { doc, unsupported } = jsonSchemaToZod(schema);
  for (const feature of unsupported) {
    warnings.push(
      `MCP tool "${toolName}" ${which} schema: ${feature} is typed as unknown (the JSON Schema still validates it at runtime)`,
    );
  }
  return doc;
}
